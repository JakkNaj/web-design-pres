export function getLanguage(url: URL): Language {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  return url.pathname.startsWith(`${base}/en/`) ? 'en' : 'cs';
}

export function languageHref(language: Language): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  return `${base}/${language === 'en' ? 'en/' : ''}`;
}

export function translate(text: string, language: Language): string {
  if (language === 'cs') return text;
  const key = text.replace(/\s+/g, ' ').trim();
  const translated = english[key];
  if (!translated) return text;
  return `${text.match(/^\s*/)?.[0] ?? ''}${translated}${text.match(/\s*$/)?.[0] ?? ''}`;
}

export const translator = (language: Language) => (text: string) => translate(text, language);
